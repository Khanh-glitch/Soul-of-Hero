#!/usr/bin/env python3
"""Generate docs/gate0/SOURCE_MANIFEST.md (Gate 0 checkpoint M0).

Every asset Gate 0 uses is copied verbatim out of Candidate B's audition folder.
This script records, for each copied file:

  * the B source path and its git blob SHA at Candidate B's commit,
  * the Gate 0 destination path and its blob SHA on this branch,
  * the SHA-256 of the working-tree bytes,

so a reviewer can prove the art was copied and not redrawn. It fails if a
destination byte-for-byte differs from its source.

    python3 tools/gate0/write_source_manifest.py [--check]
"""

from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
B_COMMIT = "e7cad36f8f21e746abefe44ac6cfa54db9a378e6"
MANIFEST = ROOT / "docs/gate0/SOURCE_MANIFEST.md"

# (Candidate B source path, Gate 0 destination path, why it is needed)
COPIES = [
    (
        "prototypes/environment_art/archive_audition/art/props.png",
        "prototypes/gate0/art/archive_props.png",
        "B's original prop atlas (128x516 RGBA). Every overlay sprite is an "
        "AtlasTexture region of this one untouched file.",
    ),
    (
        "prototypes/environment_art/archive_audition/art/props.json",
        "prototypes/gate0/art/props.json",
        "B's atlas descriptor: the 34 frame rectangles the authoring script "
        "reads. Not modified; frame names/coords are taken as authored.",
    ),
    (
        "prototypes/environment_art/archive_audition/art_src/author_archive_art.py",
        "prototypes/gate0/provenance/author_archive_art.py",
        "The generator that produced props.png, kept as provenance so the art "
        "can be regenerated and compared. Never executed by Gate 0.",
    ),
]

GIT = ("git", "-C", str(ROOT))


def git(*args: str) -> str:
    result = subprocess.run([*GIT, *args], capture_output=True, text=True, cwd=ROOT)
    if result.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout.strip()


def blob_at(commit: str, path: str) -> str:
    return git("rev-parse", f"{commit}:{path}")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def collect() -> list[dict[str, str]]:
    rows = []
    for source, destination, role in COPIES:
        source_blob = blob_at(B_COMMIT, source)
        source_bytes = subprocess.run(
            [*GIT, "show", f"{B_COMMIT}:{source}"], capture_output=True, cwd=ROOT
        ).stdout
        target = ROOT / destination
        if not target.exists():
            raise RuntimeError(f"missing destination {destination}")
        local_bytes = target.read_bytes()
        if hashlib.sha256(source_bytes).hexdigest() != hashlib.sha256(local_bytes).hexdigest():
            raise RuntimeError(
                f"{destination} differs from {B_COMMIT}:{source} - Gate 0 must copy B's "
                "art verbatim, not re-export it"
            )
        rows.append(
            {
                "source": source,
                "source_blob": source_blob,
                "destination": destination,
                "destination_blob": git("hash-object", destination),
                "sha256": sha256(target),
                "bytes": str(target.stat().st_size),
                "role": role,
            }
        )
    return rows


def render(rows: list[dict[str, str]]) -> str:
    branch = git("rev-parse", "--abbrev-ref", "HEAD")
    base = git("rev-parse", "origin/main")
    lines = [
        "# Gate 0 — Source manifest (Candidate B art provenance)",
        "",
        "Checkpoint **M0**. Generated by `tools/gate0/write_source_manifest.py`;",
        "do not hand-edit. Re-run it (or `--check`) to prove the copies still match.",
        "",
        f"- **Candidate B (art source):** `{B_COMMIT}`",
        "- **B folder:** `prototypes/environment_art/archive_audition/`",
        f"- **Gate 0 branch:** `{branch}`",
        f"- **Base content:** `origin/main` @ `{base}` (see the execution contract for"
        " the pinned Level 3 reference)",
        "",
        "Every file below is a **verbatim copy** of Candidate B's original asset.",
        "No Gate 0 art was redrawn, re-exported, recoloured or resized: the script",
        "fails if a destination byte stream differs from the B blob.",
        "",
        "## Copied files",
        "",
        "| Gate 0 destination | B source path | B blob @ `%s` | Destination blob | SHA-256 | Bytes |" % B_COMMIT[:12],
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        lines.append(
            f"| `{row['destination']}` | `{row['source']}` | `{row['source_blob']}` | "
            f"`{row['destination_blob']}` | `{row['sha256']}` | {row['bytes']} |"
        )
    lines += [
        "",
        "## What each file is for",
        "",
    ]
    for row in rows:
        lines.append(f"- **`{Path(row['destination']).name}`** — {row['role']}")
    lines += [
        "",
        "## Not copied, on purpose",
        "",
        "- `art/archive_tiles.png`, `art/tiles.json`, `art/wall_caps.png` — B's own",
        "  room tileset. Gate 0 does not add TileSet sources to Candidate A's level,",
        "  so these are not needed and copying them would imply a schema change.",
        "- `art/room_preview*.png` — B's authoring previews; Gate 0 produces its own",
        "  evidence and must not present B's previews as integration evidence.",
        "- `room.json` — B's 50x30 room. Gate 0 integrates *selected props* into A's",
        "  Level 3; importing the room layout is explicitly out of scope.",
        "- `scene/archive_room.*`, `scene/capture_archive_room.*` — B's standalone",
        "  room scene and harness. Gate 0 runs Candidate A's real `game/main.tscn`.",
        "",
        "## License / provenance",
        "",
        "The atlas and its descriptor were authored inside Candidate B's audition",
        "work on this same repository from original art, and were accepted at",
        "86/100 in `docs/design-audition/ARCHIVE_AUDITION_REPORT.md`. Gate 0 reuses",
        "them unchanged so the integration cannot launder in new, unreviewed art.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()
    try:
        rows = collect()
    except RuntimeError as error:
        print(f"MANIFEST CHECK FAILED: {error}")
        return 1
    text = render(rows)
    if args.check:
        if not MANIFEST.exists() or MANIFEST.read_text() != text:
            print("MANIFEST CHECK FAILED: docs/gate0/SOURCE_MANIFEST.md is stale")
            return 1
        print(f"MANIFEST CHECK PASSED: {len(rows)} copied assets match Candidate B exactly")
        return 0
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(text)
    print(f"wrote {MANIFEST.relative_to(ROOT)} ({len(rows)} assets)")
    for row in rows:
        print(f"  {row['destination']}  sha256={row['sha256'][:16]}...  {row['bytes']} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
