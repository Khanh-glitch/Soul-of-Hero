#!/usr/bin/env python3
"""Generate docs/gate2/SOURCE_MANIFEST.md.

Every frame Gate 2 draws comes from Candidate B's approved audition art, copied
verbatim out of B's commit; the level data is Candidate A's pinned fixture. This
script records, for each copy:

  * the source commit and source path,
  * the Gate 2 destination path,
  * the SHA-256 of both byte streams,

so a reviewer can prove the art was copied and not redrawn. It fails if a
destination differs from its source by a single byte.

    python3 tools/gate2/write_source_manifest.py [--check]
"""

from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
B_COMMIT = "e7cad36f8f21e746abefe44ac6cfa54db9a378e6"
A_COMMIT = "5ea50e9cf37791a6283bfd9a58bd634ec8aa144e9602c5b9f40f0b4600555f54"
MANIFEST = ROOT / "docs/gate2/SOURCE_MANIFEST.md"

# (source commit, source path, Gate 2 destination path, why it is needed)
COPIES = [
    (B_COMMIT,
     "prototypes/environment_art/archive_audition/art/props.png",
     "prototypes/gate2/art/props.png",
     "B's prop atlas (128x516 RGBA). Every Gate 2 prop sprite is an "
     "AtlasTexture region of this one untouched file."),
    (B_COMMIT,
     "prototypes/environment_art/archive_audition/art/props.json",
     "prototypes/gate2/art/props.json",
     "B's prop atlas descriptor: the 34 frame rectangles the authoring script "
     "reads. Frame names and coordinates are taken as authored."),
    (B_COMMIT,
     "prototypes/environment_art/archive_audition/art/archive_tiles.png",
     "prototypes/gate2/art/archive_tiles.png",
     "B's architectural tileset (128x80, 8x5 frames of 16 px). Every Gate 2 "
     "material tile - flagstone, ashlar, niche, water, decal - comes from here."),
    (B_COMMIT,
     "prototypes/environment_art/archive_audition/art/tiles.json",
     "prototypes/gate2/art/tiles.json",
     "B's tileset descriptor: the 40 named 16 px frames."),
    (B_COMMIT,
     "prototypes/environment_art/archive_audition/art/light_radial.png",
     "prototypes/gate2/art/light_radial.png",
     "The radial falloff texture the three local lanterns project."),
]


def blob(commit: str, path: str) -> bytes:
    return subprocess.run(
        ["git", "show", f"{commit}:{path}"],
        cwd=ROOT, check=True, capture_output=True,
    ).stdout


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def build() -> str:
    lines = [
        "# Gate 2 — source manifest",
        "",
        "Gate 2 adds **no new art**. Every frame it draws is Candidate B's approved",
        "audition art, copied byte-for-byte from B's commit `"
        + B_COMMIT[:12] + "`; the level data it edits is Candidate A's pinned",
        "fixture `" + A_COMMIT[:12] + "`. This file is generated by",
        "`tools/gate2/write_source_manifest.py` and verified in CI.",
        "",
        "| Gate 2 path | source | source sha256 | copy sha256 | identical |",
        "| --- | --- | --- | --- | --- |",
    ]
    problems = []
    for commit, source, dest, _why in COPIES:
        original = blob(commit, source)
        target = (ROOT / dest).read_bytes()
        same = original == target
        if not same:
            problems.append(f"{dest} differs from {commit[:12]}:{source}")
        lines.append(
            f"| `{dest}` | `{commit[:12]}:{source}` | `{sha256(original)[:16]}…` "
            f"| `{sha256(target)[:16]}…` | {'yes' if same else '**NO**'} |"
        )
    lines += ["", "## Why each file is here", ""]
    for commit, source, dest, why in COPIES:
        lines.append(f"- **`{dest}`** — {why}")
    lines += [
        "",
        "## Level data",
        "",
        "| file | provenance |",
        "| --- | --- |",
        f"| `prototypes/gate0/level_data/chapter_1_level_3_a.json` | Candidate A, "
        f"sha256 `{A_COMMIT[:16]}…` (Gate 0's pinned fixture, unmodified) |",
        "| `prototypes/gate2/level_data/chapter_1_level_3_gate2.json` | generated "
        "from the fixture above by `tools/gate2/author_gate2.py`: 12 wall cells "
        "become floor for the armarium alcove, nothing else changes |",
        "",
    ]
    if problems:
        raise SystemExit("\n".join(["SOURCE MANIFEST FAILED"] + problems))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = build()
    if args.check:
        if not MANIFEST.exists() or MANIFEST.read_text(encoding="utf-8") != text:
            print("CHECK FAILED: docs/gate2/SOURCE_MANIFEST.md is stale")
            return 1
        print("GATE2 SOURCE MANIFEST OK: 5 copies byte-identical to Candidate B")
        return 0
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(text, encoding="utf-8")
    print(f"wrote {MANIFEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
