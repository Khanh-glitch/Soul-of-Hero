#!/usr/bin/env python3
"""Gate 3 — provenance for the art Gate 3 draws with.

Gate 3 adds no art of its own: it draws with the five Candidate B files that Gate 2
already copied into `prototypes/gate2/art/`. This script proves those copies are
still byte-identical to Candidate B's original commit, and records where every
prototype-local derived document comes from.

    python3 tools/gate3/write_source_manifest.py           # write the manifest
    python3 tools/gate3/write_source_manifest.py --check    # fail if it drifted
"""

from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs/gate3/SOURCE_MANIFEST.md"
SOURCE_COMMIT = "e7cad36"
SOURCE_DIR = "prototypes/environment_art/archive_audition/art"
FILES = ["props.png", "props.json", "archive_tiles.png", "tiles.json", "light_radial.png"]


def sha256_bytes(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def original_bytes(name: str) -> bytes:
    result = subprocess.run(
        ["git", "show", f"{SOURCE_COMMIT}:{SOURCE_DIR}/{name}"],
        cwd=ROOT, capture_output=True, check=False)
    if result.returncode != 0:
        raise SystemExit(f"cannot read {SOURCE_COMMIT}:{SOURCE_DIR}/{name} from git history "
                         f"(is this a shallow clone?)")
    return result.stdout


def build() -> str:
    lines = [
        "# Gate 3 — Source manifest",
        "",
        "Generated by `tools/gate3/write_source_manifest.py`; verified in CI with `--check`.",
        "",
        "Gate 3 adds no new art. Every sprite and tile it composes comes from "
        f"Candidate B's approved audition atlas at commit `{SOURCE_COMMIT}`, "
        "`" + SOURCE_DIR + "/`, copied into `prototypes/gate2/art/` by Gate 2 and "
        "reused here byte-for-byte.",
        "",
        "| file | copy | source | sha256 | verdict |",
        "| --- | --- | --- | --- | --- |",
    ]
    ok = True
    for name in FILES:
        copy = ROOT / "prototypes/gate2/art" / name
        local = copy.read_bytes()
        original = original_bytes(name)
        same = local == original
        ok = ok and same
        lines.append(
            f"| `{name}` | `prototypes/gate2/art/{name}` | "
            f"`{SOURCE_COMMIT}:{SOURCE_DIR}/{name}` | `{sha256_bytes(local)[:16]}…` | "
            f"{'identical' if same else 'DIFFERS'} |")
    lines += [
        "",
        "## Prototype-local derived documents",
        "",
        "| document | derived from | how |",
        "| --- | --- | --- |",
        "| `prototypes/gate3/level_data/chapter_1_level_3_gate3.json` | "
        "`prototypes/gate0/level_data/chapter_1_level_3_a.json` (sha256 "
        "`5ea50e9c…`) | 75 cell edits by `tools/gate3/author_gate3.py`; entities untouched |",
        "| `prototypes/gate3/visual_placement.json` | the two atlases above plus the "
        "level document | generated and validated by `tools/gate3/author_gate3.py` |",
        "| the shade field | the material roles in `visual_placement.json` | generated "
        "at runtime by `prototypes/gate3/gate3_redesign.gd` (distance transform) |",
        "| `prototypes/gate3/art/peaks_1..4.png` | "
        "`assets/environment/dungeon/items/spikes/peaks_1..4.png` | the flat violet "
        "plate RGB(61,37,59) repainted as a dark crimson pit RGB(72,30,30) at alpha 210 "
        "and its violet shadow step RGB(54,32,48) neutralised to RGB(38,30,34); every "
        "spike pixel copied unchanged, no spike pixel added or removed. "
        "Hashes in `prototypes/gate3/art/derived_art.json`, reproducible with "
        "`tools/gate3/make_derived_art.py --check` |",
        "",
        "No production art, level data, scene or script is modified by Gate 3. The "
        "trial level is substituted inside the CI runner only.",
        "",
        "**Verdict:** " + ("all five copies are byte-identical to Candidate B. "
                          "GATE3 SOURCE MANIFEST OK" if ok else "PROVENANCE MISMATCH"),
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args(argv)
    text = build()
    if options.check:
        if not OUT.exists():
            print("GATE3 SOURCE MANIFEST: docs/gate3/SOURCE_MANIFEST.md is missing")
            return 1
        if OUT.read_text(encoding="utf-8") != text:
            print("GATE3 SOURCE MANIFEST: committed manifest differs from the sources")
            return 1
        print("GATE3 SOURCE MANIFEST OK: 5 copies byte-identical to Candidate B")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print("GATE3 SOURCE MANIFEST OK: 5 copies byte-identical to Candidate B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
