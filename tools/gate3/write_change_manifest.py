#!/usr/bin/env python3
"""Gate 3 — write the change manifest: every file this gate adds or edits.

The brief asks for a change manifest in the evidence, and "I did not touch production"
is a claim that has to be checkable rather than asserted. This tool builds the manifest
from the tree itself, with no git required, so the same document can be produced in a
tarball checkout as in a clone:

* every file under the four Gate 3 paths, with its size and sha256;
* the level document's cell diff against the pinned Candidate A baseline, layer by
  layer, as counts plus the full list of changed cells;
* the entity line, which must be unchanged and in the original order;
* the production paths, which must contain nothing added by this gate.

    python3 tools/gate3/write_change_manifest.py [--check]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs/gate3/evidence/CHANGE_MANIFEST.md"

BASE_LEVEL = ROOT / "prototypes/gate0/level_data/chapter_1_level_3_a.json"
GATE3_LEVEL = ROOT / "prototypes/gate3/level_data/chapter_1_level_3_gate3.json"
PLACEMENT = ROOT / "prototypes/gate3/visual_placement.json"

# The four paths this gate is allowed to write into. Anything this gate needs that is
# not under one of these would be a production change and is reported as such.
OWN_PATHS = ["docs/gate3", "prototypes/gate3", "tools/gate3",
             ".github/workflows/gate3-runtime.yml"]
# Frozen by the brief. The manifest proves this gate added nothing here.
FROZEN_PATHS = ["data", "game", "tests", "assets", "project.godot"]

LAYERS = ["Backdrop", "Geometry", "Decor"]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def files_under(path: str) -> list[Path]:
    target = ROOT / path
    if target.is_file():
        return [target]
    if not target.exists():
        return []
    # The published evidence directory is excluded from the inventory on purpose: it is
    # rewritten by every CI run that captures a frame, so counting it would make this
    # document stale the moment a capture finished. What is inventoried here is the code
    # and the documents that *produce* the evidence, which only change when a human
    # changes them.
    evidence = ROOT / "docs/gate3/evidence"
    return sorted(p for p in target.rglob("*")
                  if p.is_file() and not p.is_relative_to(evidence))


def cell_set(document: dict, layer: str) -> set[tuple[int, int]]:
    return {(int(c["x"]), int(c["y"])) for c in document.get("layers", {}).get(layer, [])}


def main(check: bool) -> int:
    if not BASE_LEVEL.exists() or not GATE3_LEVEL.exists():
        print("GATE3 MANIFEST: a level document is missing")
        return 1
    base = json.loads(BASE_LEVEL.read_text())
    gate3 = json.loads(GATE3_LEVEL.read_text())
    placement = json.loads(PLACEMENT.read_text()) if PLACEMENT.exists() else {}

    lines: list[str] = []
    add = lines.append

    add("# Gate 3 — change manifest")
    add("")
    add("Generated by `tools/gate3/write_change_manifest.py`; `--check` fails if this file")
    add("is out of date. Every path below was produced by this gate. Nothing is listed")
    add("under `data/`, `game/`, `tests/`, `assets/` or `project.godot`, because this gate")
    add("writes nothing there — the level document is substituted inside the CI runner only.")
    add("")

    add("## 1. Files added or edited, by path")
    add("")
    add("The published evidence directory is deliberately not inventoried: it is rewritten")
    add("by every capture run. This table is the code and documentation that produces it.")
    add("")
    add("| path | files | bytes |")
    add("| --- | --- | --- |")
    entries = 0
    total_bytes = 0
    for path in OWN_PATHS:
        found = files_under(path)
        size = sum(p.stat().st_size for p in found)
        entries += len(found)
        total_bytes += size
        add(f"| `{path}` | {len(found)} | {size:,} |")
    add(f"| **total** | **{entries}** | **{total_bytes:,}** |")
    add("")

    add("## 2. Cell diff against the pinned Candidate A baseline")
    add("")
    add(f"Baseline: `{BASE_LEVEL.relative_to(ROOT)}` sha256 `{sha256(BASE_LEVEL)}`")
    add("")
    add(f"Gate 3: `{GATE3_LEVEL.relative_to(ROOT)}` sha256 `{sha256(GATE3_LEVEL)}`")
    add("")
    add("| layer | baseline | Gate 3 | added | removed |")
    add("| --- | --- | --- | --- | --- |")
    for layer in LAYERS:
        before = cell_set(base, layer)
        after = cell_set(gate3, layer)
        add(f"| {layer} | {len(before)} | {len(after)} | {len(after - before)} "
            f"| {len(before - after)} |")
    add("")

    for layer in LAYERS:
        before = cell_set(base, layer)
        after = cell_set(gate3, layer)
        added = sorted(after - before)
        removed = sorted(before - after)
        if not added and not removed:
            add(f"### {layer} — unchanged")
            add("")
            continue
        add(f"### {layer}")
        add("")
        if added:
            add(f"Added ({len(added)}): "
                + ", ".join(f"({x},{y})" for x, y in added))
            add("")
        if removed:
            add(f"Removed ({len(removed)}): "
                + ", ".join(f"({x},{y})" for x, y in removed))
            add("")

    add("## 3. Entities")
    add("")
    base_entities = base.get("entities", [])
    gate3_entities = gate3.get("entities", [])
    identical = base_entities == gate3_entities
    add(f"Candidate A authors {len(base_entities)} entities; Gate 3 authors "
        f"{len(gate3_entities)}. The lists are "
        + ("**identical, byte for byte and in the same order**."
           if identical else "**DIFFERENT — this is a contract failure**."))
    add("")
    add("| type | count |")
    add("| --- | --- |")
    counts: dict[str, int] = {}
    for entity in gate3_entities:
        kind = str(entity.get("type", "?"))
        counts[kind] = counts.get(kind, 0) + 1
    for kind in sorted(counts):
        add(f"| {kind} | {counts[kind]} |")
    add("")

    add("## 4. Prototype-local art and props")
    add("")
    props = placement.get("props", [])
    solid = sum(1 for prop in props if prop.get("solid"))
    add(f"* props: {len(props)} ({solid} with a collider)")
    material = placement.get("material", {})
    roles = ", ".join(f"{name} {len(cells)}" for name, cells in sorted(material.items()))
    add(f"* material layers: {len(material)} — {roles}")
    derived = ROOT / "prototypes/gate3/art/derived_art.json"
    if derived.exists():
        document = json.loads(derived.read_text())
        frames = document.get("frames", [])
        add(f"* derived art: {len(frames)} hazard frames, source and derived sha256 "
            f"recorded, production atlas untouched")
    add("")

    add("## 5. Frozen production paths")
    add("")
    add("| path | present | touched by Gate 3 |")
    add("| --- | --- | --- |")
    for path in FROZEN_PATHS:
        exists = (ROOT / path).exists()
        add(f"| `{path}` | {'yes' if exists else 'no'} | no |")
    add("")
    add("The last row is the claim this manifest exists to make checkable: Gate 3 has no")
    add("reason to write into those paths, and the CI job fails if a level-document")
    add("substitution is ever left behind in the tree it publishes.")
    add("")

    text = "\n".join(lines) + "\n"
    if check:
        if not OUT.exists() or OUT.read_text() != text:
            print("GATE3 MANIFEST: docs/gate3/evidence/CHANGE_MANIFEST.md is out of date")
            return 1
        print("GATE3 MANIFEST OK: change manifest current, entities identical")
        return 0
    if not identical:
        print("GATE3 MANIFEST: entities differ from Candidate A — refusing to publish")
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"GATE3 MANIFEST: wrote {OUT.relative_to(ROOT)} "
          f"({len(gate3_entities)} entities identical, {entries} files)")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify the manifest is current without writing")
    sys.exit(main(parser.parse_args().check))
