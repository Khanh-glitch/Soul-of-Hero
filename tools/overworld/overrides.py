#!/usr/bin/env python3
"""Hybrid asset pipeline: generated art, plus hand-painted overrides on top.

The overworld atlas is generated by `art.py` / `art_props.py`. That is fast and
reproducible, and it is also a dead end for art direction: the moment a frame
needs a human's hand, either the generator is hacked until it can never change
again, or the hand work is overwritten by the next regeneration.

This module is the escape hatch, and it is deliberately non-destructive:

    assets/environment/overworld/overrides/tiles/<frame>.png
    assets/environment/overworld/overrides/props/<frame>.png

Every file in there replaces exactly one frame of the generated sheet, at the
frame's own size. Nothing in the generator knows the names: `compose()` runs
after the sheet is built and pastes whatever it finds, so adding a hand-painted
tree is dropping in one PNG, and deleting that PNG restores the generated frame
on the next run. A regeneration never loses manual work, and the override never
has to be copied around — it is applied at build time, in memory.

`data/overworld/art_manifest.json` records, per frame, whether the pixel on
disk came from the generator or from an override, the frame's size and source
file, and a checksum of the composited result. That manifest is what the license
audit and the CI check read: the question "is any pixel in this game of unknown
provenance" is answered from data, not from a doc that drifts.

    python3 tools/overworld/overrides.py --report     # what is overridden today
    python3 tools/overworld/overrides.py --list       # every override file
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os

from PIL import Image

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
ART = os.path.join(ROOT, "assets", "environment", "overworld")
OVERRIDES = os.path.join(ART, "overrides")
DATA = os.path.join(ROOT, "data", "overworld")
MANIFEST = os.path.join(DATA, "art_manifest.json")

SHEETS = {
    "tiles": {
        "image": os.path.join(ART, "overworld_tiles.png"),
        "index": os.path.join(DATA, "overworld_tiles.json"),
    },
    "props": {
        "image": os.path.join(ART, "overworld_props.png"),
        "index": os.path.join(DATA, "overworld_props.json"),
    },
}

# Provenance for everything the generators draw. They are original works written
# in this repository (tools/overworld/art.py, art_props.py), so the project owns
# them outright; the point of listing it is that the audit is checkable, not that
# the value is surprising.
GENERATED_LICENSE = "original"
GENERATED_SOURCE = "tools/overworld"


def override_dir(sheet_name: str) -> str:
    return os.path.join(OVERRIDES, sheet_name)


def available(sheet_name: str) -> dict[str, str]:
    """Frame name -> override PNG path, for one sheet."""
    directory = override_dir(sheet_name)
    out: dict[str, str] = {}
    if not os.path.isdir(directory):
        return out
    for entry in sorted(os.listdir(directory)):
        if not entry.lower().endswith(".png"):
            continue
        out[entry[:-4]] = os.path.join(directory, entry)
    return out


def _frame_index(sheet_name: str) -> dict:
    """Frame name -> [x, y, w, h], for either sheet's JSON shape.

    The tile atlas stores a flat `index` map; the prop atlas stores `frames` as
    objects with named fields. Both are normalised here so the rest of the module
    never has to care which sheet it is looking at.
    """
    with open(SHEETS[sheet_name]["index"]) as handle:
        document = json.load(handle)
    if "index" in document:
        return {name: list(rect) for name, rect in document["index"].items()}
    out: dict[str, list[int]] = {}
    for name, frame in document.get("frames", {}).items():
        out[name] = [int(frame.get("x", 0)), int(frame.get("y", 0)),
                     int(frame.get("w", 16)), int(frame.get("h", 16))]
    return out


def compose(sheet_name: str, verbose: bool = True) -> dict:
    """Paste every override onto the generated sheet, in place.

    Returns the per-frame manifest for this sheet. An override whose name is not
    a frame, or whose size does not match the frame, is reported and skipped: a
    typo must not silently blank part of the atlas, and a resized frame must not
    shift every rectangle after it in the index.
    """
    sheet = Image.open(SHEETS[sheet_name]["image"]).convert("RGBA")
    index = _frame_index(sheet_name)
    overrides = available(sheet_name)
    frames: dict[str, dict] = {
        name: {
            "rect": list(rect),
            "source": "generated",
            "license": GENERATED_LICENSE,
            "origin": GENERATED_SOURCE,
        }
        for name, rect in index.items()
    }
    applied = 0
    skipped: list[str] = []
    for name, path in overrides.items():
        rect = index.get(name)
        if rect is None:
            skipped.append("%s (no such frame)" % name)
            continue
        x, y, w, h = rect
        art = Image.open(path).convert("RGBA")
        if art.size != (w, h):
            skipped.append("%s (%dx%d, frame is %dx%d)" % (name, art.width, art.height, w, h))
            continue
        sheet.alpha_composite(art, (x, y))
        frames[name]["source"] = "override"
        frames[name]["origin"] = os.path.relpath(path, ROOT)
        frames[name]["license"] = "original"
        applied += 1
    if applied:
        # Writing only when something changed keeps a no-override run from
        # touching the binary that git would then show as dirty.
        sheet.save(SHEETS[sheet_name]["image"])
    if verbose:
        print("%-6s %3d frames, %d overridden, %d skipped" % (sheet_name, len(index), applied, len(skipped)))
        for reason in skipped:
            print("  SKIP %s" % reason)
    return {"frames": frames, "applied": applied, "skipped": skipped}


def write_manifest(report: dict[str, dict]) -> dict:
    document = {
        "sheet_order": sorted(report.keys()),
        "sheets": {},
    }
    for sheet_name, info in report.items():
        frame_count = len(info["frames"])
        overridden = sum(1 for frame in info["frames"].values() if frame["source"] == "override")
        image_path = SHEETS[sheet_name]["image"]
        with open(image_path, "rb") as handle:
            digest = hashlib.sha256(handle.read()).hexdigest()[:16]
        document["sheets"][sheet_name] = {
            "image": os.path.relpath(image_path, ROOT),
            "sha256_16": digest,
            "frames": frame_count,
            "overridden": overridden,
            "skipped": info["skipped"],
            "index": info["frames"],
        }
    os.makedirs(DATA, exist_ok=True)
    with open(MANIFEST, "w") as handle:
        json.dump(document, handle, indent=1, sort_keys=True)
    return document


def load_manifest() -> dict:
    if not os.path.exists(MANIFEST):
        return {}
    with open(MANIFEST) as handle:
        return json.load(handle)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--report", action="store_true", help="summarise the manifest")
    parser.add_argument("--list", action="store_true", help="list override files")
    parser.add_argument("--compose", action="store_true", help="apply overrides and rewrite the manifest")
    args = parser.parse_args()

    if args.list:
        for sheet_name in sorted(SHEETS):
            found = available(sheet_name)
            print("%s: %d override file(s)" % (sheet_name, len(found)))
            for name, path in found.items():
                print("  %-24s %s" % (name, os.path.relpath(path, ROOT)))
        return 0

    if args.compose:
        report = {name: compose(name) for name in sorted(SHEETS)}
        document = write_manifest(report)
        total = sum(sheet["overridden"] for sheet in document["sheets"].values())
        print("manifest written: %s (%d overridden frames)" % (os.path.relpath(MANIFEST, ROOT), total))
        return 0

    document = load_manifest()
    if not document:
        print("no manifest yet - run with --compose")
        return 0
    for sheet_name in document["sheet_order"]:
        sheet = document["sheets"][sheet_name]
        print("%-6s %3d frames, %d overridden, sha %s"
              % (sheet_name, sheet["frames"], sheet["overridden"], sheet["sha256_16"]))
        for name, frame in sorted(sheet["index"].items()):
            if frame["source"] == "override":
                print("  %-24s %s" % (name, frame["origin"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
