export function drawArcanaCore(g:CanvasRenderingContext2D,id:number,base:string,light:string){
 const rows=CORE_MOTIFS[id-1];if(!rows)throw new RangeError('Unknown ARCANA Core');
 // Octagonal, outlined physical vessel, with local glints and a skill motif.
 const pixel=(x:number,y:number,color:string)=>{g.fillStyle=color;g.fillRect(x,y,1,1);};
 for(let y=1;y<15;y++)for(let x=1;x<15;x++){const dx=Math.abs(x-7.5),dy=Math.abs(y-7.5);if(dx>6.5||dy>6.5||dx+dy>11)continue;const rim=dx>5.5||dy>5.5||dx+dy>9;pixel(x,y,rim?'#302536':base);}
 for(let x=5;x<11;x++)pixel(x,2,light);pixel(3,4,light);pixel(12,11,light);
 for(let y=0;y<9;y++)for(let x=0;x<9;x++){const c=rows[y][x];if(c==='#')pixel(x+3,y+3,light);else if(c==='o')pixel(x+3,y+3,'#110c20');}
}
