/**
 * G1B batch 2 — room / floor / road chest ecology.
 *  default      : audits the frozen ecology (ids, tiles, storeys, families) against the contract and the census file
 *  G1B_ECOLOGY=1: re-surveys the compiled runtime (≈2.5 min) and requires the frozen data to be byte-identical
 *  G1B_WRITE=1  : re-surveys and rewrites src/game/g1b-ecology.generated.ts + evidence/g1b/census/*
 */
import { describe, it, expect } from 'vitest';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { G1B_CHESTS, G1B_SOURCE_SITES, G1B_BASE_SOURCE_SITES, G1B_ECOLOGY_SOURCES, G1B_FIXTURES, G1B_GATE_BY_ID, G1B_LAYOUT_REVISION } from '../src/game/g1b';

const GEN = resolve(__dirname, '../src/game/g1b-ecology.generated.ts');
const DIR = resolve(__dirname, '../evidence/g1b/census');
const emit = (sources: any[]) => `/**
 * GENERATED by tests/g1b-ecology.test.ts (G1B_WRITE=1). Do not edit by hand.
 * Batch-3 room / floor / road ecology: ADD-ONLY over the frozen Batch-2 roster (427 ecology ids, kept verbatim).
 * New chest sources are added where the compiled runtime's real geometry allows more; no Batch-2 chest is moved or
 * dropped. gx,gy are global U=0.5 tiles; level is the storey; ax,ay is the one approach tile kept free.
 */
import type { G1bSourceSite } from './g1b-sources.generated';
/** Bumped whenever the set of source ids changes; persist.ts migrates older saves by adding the missing sources closed. */
export const G1B_LAYOUT_REVISION = 4;
export const G1B_ECOLOGY_SOURCES: readonly G1bSourceSite[] = [
${sources.map(s => '  ' + JSON.stringify(s) + ',').join('\n')}
];
`;

describe('G1B ecology (frozen data)', () => {
  it('adds sources without touching the 130 round-1 ids, on distinct tiles and real variants', () => {
    expect(G1B_BASE_SOURCE_SITES.length).toBe(130);
    expect(G1B_SOURCE_SITES.slice(0, 130)).toEqual(G1B_BASE_SOURCE_SITES);
    expect(G1B_LAYOUT_REVISION).toBe(4);
    const ids = new Set<string>(), tiles = new Set<string>();
    for (const s of G1B_SOURCE_SITES) { expect(ids.has(s.id), s.id).toBe(false); ids.add(s.id); const k = `${s.level ?? 0}:${s.gx},${s.gy}`; expect(tiles.has(k), k).toBe(false); tiles.add(k); expect(G1B_CHESTS[s.variant], s.variant).toBeTruthy(); }
    for (const f of G1B_FIXTURES) expect(tiles.has(`0:${f.gx},${f.gy}`)).toBe(false);
    for (const s of G1B_ECOLOGY_SOURCES) {
      expect(s.id).toMatch(/^veyra\.g1b:[a-z0-9_]+:(supply|toolbox|military|food|medical)_(damaged|low|mid|high):[a-z0-9_.]+\.\d\d$/);
      expect(s.id.split(':')[2]).toBe(s.variant); expect(s.id.split(':')[1]).toBe(s.site);
      expect([-1, 0, 1, 2]).toContain(s.level); expect(typeof s.space).toBe('string');
      expect(Math.abs(s.ax! - s.gx) + Math.abs(s.ay! - s.gy)).toBe(1);                       // the approach tile is a 4-neighbour
      if (s.gate) { expect(G1B_GATE_BY_ID[s.gate]).toBeTruthy(); expect(s.zone).toBe('CARD_ROOM'); }
      if (s.zone === 'ROAD') expect(s.level).toBe(0);
    }
  });
  it('matches the census: every source (base + added) belongs to exactly one surveyed space or road feature', () => {
    if (!G1B_ECOLOGY_SOURCES.length) return;
    const C = JSON.parse(readFileSync(resolve(DIR, 'G1B_SPACE_CENSUS.json'), 'utf8'));
    // the census owns EVERY compiled runtime chest source (base + added) exactly once — no unknown, no unowned, no duplicate
    const owned = new Map<string, number>();
    for (const r of [...C.spaces, ...C.roads]) for (const id of [...r.base, ...r.added]) owned.set(id, (owned.get(id) ?? 0) + 1);
    const runtime = new Set<string>([...G1B_BASE_SOURCE_SITES.map((q: any) => q.id), ...G1B_ECOLOGY_SOURCES.map((q: any) => q.id)]);
    for (const s of G1B_ECOLOGY_SOURCES) expect(owned.get(s.id), s.id).toBe(1);
    for (const b of G1B_BASE_SOURCE_SITES) expect(owned.get(b.id), b.id).toBe(1);
    for (const [id, n] of owned) expect(n, id).toBe(1);                      // no duplicated attribution
    expect(owned.size).toBe(runtime.size);                                    // no unknown / unowned source
    // no source in a combat floor, another owner's shell, or an unreachable space; a transit lane may hold a chest
    // ONLY where the survey recorded a real wall pocket / alcove (batch 3 physical pass), never in the walking line
    for (const r of C.spaces) {
      if (['arena', 'shell'].includes(r.kind) || !r.reachable) expect([...r.base, ...r.added].length, r.id).toBe(0);
      if (r.kind === 'transit' && r.added.length) expect(r.reasons.some((q: string) => /wall pocket|physical placement/.test(q)), r.id).toBe(true);
    }
    // every space that holds a chest explains itself
    for (const r of C.spaces) if ([...r.base, ...r.added].length) expect(r.reasons.length, r.id).toBeGreaterThan(1);
  });
});

describe.runIf(process.env.G1B_ECOLOGY === '1' || process.env.G1B_WRITE === '1')('G1B ecology (survey of the compiled runtime)', () => {
  it('re-surveys Veyra and reproduces the frozen ecology', async () => {
    const { buildEcology } = await import('./helpers/g1b-ecology');
    const E = buildEcology();
    const text = emit(E.sources);
    if (process.env.G1B_WRITE === '1') {
      mkdirSync(DIR, { recursive: true });
      writeFileSync(GEN, text);
      writeFileSync(resolve(DIR, 'G1B_SPACE_CENSUS.json'), JSON.stringify({ schema: 'soh.g1b.space-census.v3', layoutRevision: G1B_LAYOUT_REVISION, spaces: E.spaces, roads: E.roads, notes: E.notes, baseSpace: E.baseLevels }, null, 1));
    } else expect(text).toBe(readFileSync(GEN, 'utf8'));
  }, 1800000);
});
