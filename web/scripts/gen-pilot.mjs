#!/usr/bin/env node
// Generates web/src/game/pixelfx/pilot.ts + web/src/game/pixelfx/pilot-assets/ from the
// accepted PixelFX Foundry pack (assets/pixelfx_foundry). The pilot set is the subset of
// effects embedded into the standalone single-file HTML build (mode A). The FULL 244-effect
// pack is served lazily from web/pixelfx-assets/ (mode B, rebuilt with the documented
// Foundry intake command — see web/README_PIXELFX.md).
//
// Usage: node scripts/gen-pilot.mjs [--foundry ../../assets/pixelfx_foundry]
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, statSync } from 'fs';
import { join, dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, '..');
const args = process.argv.slice(2);
const gi = args.indexOf('--foundry');
const foundry = resolve(webRoot, gi >= 0 ? args[gi + 1] : '../assets/pixelfx_foundry');

export const PILOT_IDS = [
  'ice/ice-lance', 'arcane/arcane-orb', 'shadow/black-hole', 'fire/fireball',
  'nature/quake', 'lightning/chain-lightning', 'ice/frost-nova',
  'moves/ice-lance-throw', 'impacts/impact-frame', 'arcane/spell-charge',
  'explosions/small-explosion',
];

const index = JSON.parse(readFileSync(join(foundry, 'index.json'), 'utf8'));
const outDir = join(webRoot, 'src/game/pixelfx/pilot-assets');
mkdirSync(outDir, { recursive: true });

const imports = [];
const urlOf = new Map(); // original atlas path -> imported url identifier
let n = 0;
const pilotEffects = [];

for (const id of PILOT_IDS) {
  const e = index.effects.find(x => x.id === id);
  if (!e) throw new Error('pilot id not in manifest: ' + id);
  if (e.export.state !== 'PARITY_PASS') throw new Error('pilot id not PARITY_PASS: ' + id);
  const trimmed = {
    id: e.id, category: e.category, name: e.name, desc: e.desc,
    meta: e.meta, presentation: e.presentation,
    export: {
      state: e.export.state, frames: e.export.frames, fps: e.export.fps,
      frameSize: e.export.frameSize, pivot: e.export.pivot,
      coreBounds: e.export.coreBounds, focalPoint: e.export.focalPoint,
      lightEnergy: e.export.lightEnergy, pages: { combined: [], light: [] },
    },
  };
  for (const chan of ['combined', 'light']) {
    for (const page of e.export.pages[chan]) {
      const src = join(foundry, page.path);
      const rel = 'pilot-assets/' + page.path.replace(/^assets\//, '');
      const dst = join(webRoot, 'src/game/pixelfx', rel);
      mkdirSync(dirname(dst), { recursive: true });
      copyFileSync(src, dst);
      const ident = 'u' + (n++);
      imports.push(`import ${ident} from './${rel}?url';`);
      urlOf.set(page.path + '::' + chan, ident);
      trimmed.export.pages[chan].push({ ...page, path: ident });
    }
  }
  pilotEffects.push(trimmed);
}

// rewrite page.path identifiers into the url map at module scope
const effectJson = JSON.stringify(pilotEffects, null, 1)
  .replace(/"path": "(u\d+)"/g, (m, ident) => `"path": ${ident}`);
// but channel matters only for uniqueness of identifier; combined/light got distinct idents already.

const header = `// GENERATED by web/scripts/gen-pilot.mjs — do not edit by hand.
// Embedded pilot FX pack (subset of the accepted PixelFX Foundry, upstream
// github.com/patch-gg/pixelfx @ ${index.upstream_sha}, MIT). Regenerate:
//   node scripts/gen-pilot.mjs
`;
writeFileSync(join(webRoot, 'src/game/pixelfx/pilot.ts'),
  header + imports.join('\n') + '\n\nexport const PILOT_MANIFEST = ' + effectJson + ';\n');

let bytes = 0;
const walk = d => { for (const f of readdirSync(d)) { const p = join(d, f); const st = statSync(p); if (st.isDirectory()) walk(p); else bytes += st.size; } };
walk(outDir);
console.log('pilot.ts written:', pilotEffects.length, 'effects,', (bytes / 1048576).toFixed(2), 'MB raw atlases embedded');
