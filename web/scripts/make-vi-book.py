#!/usr/bin/env python3
"""Assemble src/game/i18n-vi-book.ts from the phrase lists in i18n/vi/*.txt (run from web/)."""
import glob, sys
out = []
for path in sorted(glob.glob('i18n/vi/*.txt')):
    for n, line in enumerate(open(path, encoding='utf8').read().split('\n'), 1):
        t = line.strip()
        if not t: continue
        if not t.startswith('#') and ' => ' not in t: sys.exit(f'{path}:{n}: no " => " in: {t[:60]}')
        if '`' in t or '${' in t or '\\' in t: sys.exit(f'{path}:{n}: backtick, backslash or ${{ not allowed')
        out.append(t)
body = '\n'.join(out)
open('src/game/i18n-vi-book.ts', 'w', encoding='utf8').write(
    '// GENERATED by scripts/make-vi-book.py from i18n/vi/*.txt. Edit those files, not this one.\n'
    '// Format and rules: see i18n-vi.ts.\nexport const VI_BOOK = `\n' + body + '\n`;\n')
print(len([l for l in out if not l.startswith('#')]), 'phrases')
