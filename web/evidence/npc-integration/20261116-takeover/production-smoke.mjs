import chromium from '@sparticuz/chromium';
import { chromium as pw } from 'playwright';
import fs from 'node:fs';
const executablePath = await chromium.executablePath();
const b = await pw.launch({executablePath, args:chromium.args, headless:true, env:{...process.env, LD_LIBRARY_PATH:'/tmp/al2023/lib:'+ (process.env.LD_LIBRARY_PATH||'')}});
const page = await b.newPage({viewport:{width:640,height:360},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto('http://localhost:5200/',{waitUntil:'load'});
await page.getByText('New run').first().click();
await page.getByText('VEYRA · Unified World').first().click();
await page.getByText('Begin the 14 days').click();
await page.locator('canvas').first().waitFor({state:'visible',timeout:90000});
await page.waitForTimeout(3000);
const output='web/evidence/npc-integration/20261116-takeover';fs.mkdirSync(output,{recursive:true});
await page.screenshot({path:output+'/production-640x360.png'});
const snapshot=await page.evaluate(()=>({title:document.title,canvas:[...document.querySelectorAll('canvas')].map(c=>({width:c.width,height:c.height})),qaMutableStatePresent:!!window.__soh}));
const frames=await page.evaluate(()=>new Promise(resolve=>{const times=[];let prev;function frame(t){if(prev)times.push(t-prev);prev=t;if(times.length<300)requestAnimationFrame(frame);else {times.sort((a,b)=>a-b);resolve({samples:times.length,mean:times.reduce((a,b)=>a+b,0)/times.length,p95:times[Math.floor(times.length*.95)],p99:times[Math.floor(times.length*.99)]});}}requestAnimationFrame(frame);}));
fs.writeFileSync(output+'/production-smoke.json',JSON.stringify({snapshot,frames,errors,scope:'Production build d853540: title to fresh Veyra run through ordinary controls. No NPC scenario or comparative performance claim.'},null,2));
console.log(JSON.stringify({snapshot,frames,errors},null,2));await b.close();
